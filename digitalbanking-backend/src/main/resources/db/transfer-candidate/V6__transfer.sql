CREATE TABLE banking.transfer (
    transfer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_no VARCHAR(32) NOT NULL,
    customer_id BIGINT NOT NULL,
    initiated_by_user_id BIGINT NOT NULL,
    source_account_id BIGINT NOT NULL,
    destination_account_id BIGINT NOT NULL,
    amount NUMERIC(19, 2) NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'VND',
    description VARCHAR(255),
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    failure_code VARCHAR(32),
    failure_message VARCHAR(255),
    correlation_id VARCHAR(64) NOT NULL,
    step_up_challenge_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ,
    failed_at TIMESTAMPTZ,

    -- Durable metadata only; a lease by itself does not authorize money writes.
    attempt_epoch BIGINT NOT NULL DEFAULT 0,
    attempt_token UUID,
    attempt_owner VARCHAR(128),
    attempt_lease_expires_at TIMESTAMPTZ,
    attempt_state VARCHAR(24) NOT NULL DEFAULT 'IDLE',
    recovery_attempt_count INTEGER NOT NULL DEFAULT 0,
    recovery_first_attempt_at TIMESTAMPTZ,
    recovery_next_attempt_at TIMESTAMPTZ,

    CONSTRAINT uq_transfer_reference UNIQUE (reference_no),
    CONSTRAINT ck_transfer_reference_length CHECK (char_length(reference_no) BETWEEN 1 AND 32),
    CONSTRAINT ck_transfer_amount CHECK (amount > 0 AND amount <> 'NaN'::NUMERIC),
    CONSTRAINT ck_transfer_currency CHECK (currency = 'VND'),
    CONSTRAINT ck_transfer_distinct_accounts CHECK (source_account_id <> destination_account_id),
    CONSTRAINT ck_transfer_status CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_transfer_terminal_data CHECK (
        (status = 'PENDING' AND completed_at IS NULL AND failed_at IS NULL)
        OR (status = 'COMPLETED' AND completed_at IS NOT NULL AND failed_at IS NULL)
        OR (status = 'FAILED' AND failed_at IS NOT NULL AND completed_at IS NULL AND failure_code IS NOT NULL)
    ),
    CONSTRAINT ck_transfer_attempt_epoch CHECK (attempt_epoch >= 0),
    CONSTRAINT ck_transfer_attempt_state CHECK (attempt_state IN ('IDLE', 'CLAIMED', 'FAILURE_PENDING', 'MANUAL', 'DONE')),
    CONSTRAINT ck_transfer_attempt_claim CHECK (
        (attempt_state IN ('CLAIMED', 'FAILURE_PENDING') AND attempt_token IS NOT NULL
            AND attempt_owner IS NOT NULL AND char_length(btrim(attempt_owner)) > 0
            AND attempt_lease_expires_at IS NOT NULL)
        OR (attempt_state IN ('IDLE', 'MANUAL', 'DONE') AND attempt_token IS NULL
            AND attempt_owner IS NULL AND attempt_lease_expires_at IS NULL)
    ),
    CONSTRAINT ck_transfer_recovery_attempts CHECK (
        recovery_attempt_count >= 0 AND
        ((recovery_attempt_count = 0 AND recovery_first_attempt_at IS NULL)
            OR (recovery_attempt_count > 0 AND recovery_first_attempt_at IS NOT NULL))
    ),
    CONSTRAINT fk_transfer_customer FOREIGN KEY (customer_id)
        REFERENCES banking.customer (customer_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_transfer_user FOREIGN KEY (initiated_by_user_id)
        REFERENCES banking.app_user (user_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_transfer_source FOREIGN KEY (source_account_id)
        REFERENCES banking.account (account_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_transfer_destination FOREIGN KEY (destination_account_id)
        REFERENCES banking.account (account_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_transfer_challenge FOREIGN KEY (step_up_challenge_id)
        REFERENCES banking.auth_challenge (challenge_id) ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE INDEX ix_transfer_customer_time ON banking.transfer (customer_id, created_at DESC);
CREATE INDEX ix_transfer_source_time ON banking.transfer (source_account_id, created_at DESC);
CREATE INDEX ix_transfer_destination_time ON banking.transfer (destination_account_id, created_at DESC);
CREATE INDEX ix_transfer_status_time ON banking.transfer (status, created_at);
CREATE INDEX ix_transfer_correlation ON banking.transfer (correlation_id);
CREATE UNIQUE INDEX uq_transfer_step_up_challenge ON banking.transfer (step_up_challenge_id)
    WHERE step_up_challenge_id IS NOT NULL;

CREATE FUNCTION banking.guard_transfer_immutable_fields() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.reference_no IS DISTINCT FROM OLD.reference_no THEN
        RAISE EXCEPTION 'transfer reference is immutable' USING ERRCODE = '23514';
    END IF;
    IF OLD.status IN ('COMPLETED', 'FAILED') AND (
        NEW.status IS DISTINCT FROM OLD.status OR NEW.amount IS DISTINCT FROM OLD.amount
        OR NEW.source_account_id IS DISTINCT FROM OLD.source_account_id
        OR NEW.destination_account_id IS DISTINCT FROM OLD.destination_account_id
    ) THEN
        RAISE EXCEPTION 'terminal transfer fields are immutable' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_transfer_immutable_fields
    BEFORE UPDATE ON banking.transfer FOR EACH ROW
    EXECUTE FUNCTION banking.guard_transfer_immutable_fields();

CREATE TABLE banking.idempotency_record (
    idempotency_key VARCHAR(255) PRIMARY KEY,
    request_hash CHAR(64) NOT NULL,
    transfer_id BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'RECEIVED',
    response_status SMALLINT,
    response_body JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ NOT NULL,
    ttl_t1_seconds BIGINT NOT NULL,
    ttl_t1_config_version VARCHAR(128) NOT NULL,
    ttl_terminal_seconds BIGINT,
    ttl_terminal_config_version VARCHAR(128),

    CONSTRAINT uq_idempotency_transfer UNIQUE (transfer_id),
    CONSTRAINT fk_idempotency_transfer FOREIGN KEY (transfer_id)
        REFERENCES banking.transfer (transfer_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_idempotency_key_length CHECK (char_length(idempotency_key) BETWEEN 1 AND 255),
    CONSTRAINT ck_idempotency_status CHECK (status IN ('RECEIVED', 'IN_PROGRESS', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_idempotency_response_status CHECK (response_status IS NULL OR response_status BETWEEN 100 AND 599),
    CONSTRAINT ck_idempotency_terminal_data CHECK (
        status NOT IN ('COMPLETED', 'FAILED') OR (completed_at IS NOT NULL AND response_status IS NOT NULL)
    ),
    CONSTRAINT ck_idempotency_expiry CHECK (expires_at > created_at),
    CONSTRAINT ck_idempotency_t1_ttl CHECK (
        ttl_t1_seconds >= 86400 AND char_length(btrim(ttl_t1_config_version)) > 0
    ),
    CONSTRAINT ck_idempotency_terminal_ttl CHECK (
        (status IN ('RECEIVED', 'IN_PROGRESS') AND ttl_terminal_seconds IS NULL AND ttl_terminal_config_version IS NULL)
        OR (status IN ('COMPLETED', 'FAILED') AND ttl_terminal_seconds IS NOT NULL
            AND ttl_terminal_seconds >= 86400 AND ttl_terminal_config_version IS NOT NULL
            AND char_length(btrim(ttl_terminal_config_version)) > 0)
    )
);

CREATE INDEX ix_idempotency_expires ON banking.idempotency_record (expires_at);
CREATE INDEX ix_idempotency_status ON banking.idempotency_record (status);
